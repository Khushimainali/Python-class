# Write a Python program that:
# • Stores the length and width of a rectangle
# • Calculates the area  (length × width)
# • Calculates the perimeter  (2 × (length + width))
# • Prints both results with labels.
length = 7
width = 5

area = length * width
perimeter = 2 * (length + width)

print("Area:", area)
print("Perimeter:", perimeter)